"""Internal egglog language for scalar algebra, complex operations and index sums."""

from __future__ import annotations

from egglog import BigInt, Expr, i64


class Scalar(Expr):
    """Scalar algebra and conjugation; opaque atoms may also hold tensors or forms."""

    @classmethod
    def integer(cls, value: BigInt) -> Scalar: ...

    @classmethod
    def atom(cls, key: i64) -> Scalar: ...

    @classmethod
    def at(cls, key: i64, index: i64, extent: i64) -> Scalar: ...

    @classmethod
    def delta(cls, extent: i64, first: i64, second: i64) -> Scalar: ...

    @classmethod
    def summed(cls, body: Scalar, index: i64, extent: i64) -> Scalar: ...

    def __add__(self, other: Scalar) -> Scalar: ...

    def __mul__(self, other: Scalar) -> Scalar: ...

    def conjugate(self) -> Scalar: ...

    def real_part(self) -> Scalar: ...

    def imaginary_part(self) -> Scalar: ...

    def power(self, exponent: Scalar) -> Scalar: ...

    def absolute(self) -> Scalar: ...

    def logarithm(self) -> Scalar: ...
